import { chromium } from 'playwright'
import assert from 'node:assert/strict'

const base = process.env.MC3_BASE_URL || 'http://127.0.0.1:8000'
const browser = await chromium.launch({ channel: 'msedge', headless: true })
const page = await browser.newPage({ viewport: { width: 1366, height: 768 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const count = value => page.waitForFunction(value => document.querySelector('[data-testid="communication-count"]')?.textContent === String(value), value)
const exportButton = page.getByRole('button', { name: '↓ 导出报告', exact: true })
try {
  await page.goto(base, { waitUntil: 'networkidle' })
  await page.getByTestId('workspace-patterns').click()
  await count(584)
  await page.route('**/api/overview?**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Simulated unavailable overview' } }) }))
  await page.getByTestId('end-date').fill('2040-10-07')
  await page.getByRole('alert').filter({ hasText: 'Simulated unavailable overview' }).waitFor()
  assert.equal(await exportButton.isDisabled(), true, 'A failed refresh must never export old statistics with new filters')
  assert.match(await page.locator('.context-line').innerText(), /未同步/)
  await page.unroute('**/api/overview?**')
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await count(301)
  assert.equal(await exportButton.isEnabled(), true)
  console.log('PASS Failed partial refresh blocks export; retry restores a coherent scope')

  await page.route('**/api/graph?**', async route => {
    const end = new URL(route.request().url()).searchParams.get('end')
    if (end === '2040-10-14') await new Promise(resolve => setTimeout(resolve, 500))
    await route.continue()
  })
  await page.getByTestId('end-date').fill('2040-10-14')
  assert.equal(await exportButton.isDisabled(), true)
  await page.getByTestId('end-date').fill('2040-10-01')
  await count(44)
  await page.waitForTimeout(600)
  assert.equal(await page.getByTestId('communication-count').innerText(), '44')
  const pending = page.waitForEvent('download')
  await exportButton.click()
  const stream = await (await pending).createReadStream()
  const chunks = []
  for await (const chunk of stream) chunks.push(chunk)
  const report = await browser.newPage()
  await report.setContent(Buffer.concat(chunks).toString('utf8'))
  assert.equal(await report.locator('.message-record').count(), 44)
  assert.match(await report.locator('body').innerText(), /44 条通信/)
  await report.close()
  console.log('PASS Rapid filters and partial response delays keep the exported report coherent')
  await page.unroute('**/api/graph?**')
  await page.getByTestId('reset').click()
  await count(584)
  const loops = page.locator('.graph-edge').filter({ has: page.locator('title', { hasText: /^Davis → Davis/ }) })
  assert.equal(await loops.count(), 1)
  assert((await loops.evaluate(node => node.getTotalLength())) > 20, 'Self-loop must have a visible curve, not a zero-length path')
  await loops.focus()
  await page.keyboard.press('Enter')
  await page.waitForFunction(() => document.querySelector('.reader-layout')?.textContent.includes('原始通信 6 条'))
  console.log('PASS Visible self-loop opens its six source messages using the keyboard')
  await page.getByTestId('reset').click()
  await count(584)
  await page.getByTestId('workspace-groups').click()
  await page.getByLabel('主题数量', { exact: true }).selectOption('8')
  await page.waitForFunction(() => document.querySelectorAll('[data-testid="topic-matrix"] thead button').length === 8)
  const topicColors = await page.locator('[data-testid="topic-matrix"] thead button i').evaluateAll(nodes => nodes.map(node => getComputedStyle(node).backgroundColor))
  assert.equal(new Set(topicColors).size, 8, 'Eight topics need eight distinct colors')
  await page.getByLabel('主题矩阵度量').selectOption('share')
  const cells = await page.getByTestId('topic-cell').evaluateAll(nodes => nodes.map(node => ({ count: Number(node.dataset.count), share: Number(node.dataset.share), text: node.textContent })))
  for (let i = 0; i < cells.length; i += 8) {
    const row = cells.slice(i, i + 8), total = row.reduce((sum, cell) => sum + cell.count, 0)
    assert(Math.abs(row.reduce((sum, cell) => sum + cell.share, 0) - (total ? 1 : 0)) < 1e-5)
    for (const cell of row) assert(Math.abs(cell.share - (total ? cell.count / total : 0)) < 1e-6)
  }
  await page.getByTestId('topic-cell').filter({ hasText: /%/ }).first().click()
  await page.getByLabel('原文抽样方式').selectOption('boundary')
  await page.getByTestId('topic-sample').first().waitFor()
  assert.match(await page.getByTestId('topic-sample').first().innerText(), /权重差/)
  console.log('PASS Eight distinct topic colors, normalized group shares and boundary evidence are inspectable')
  let releaseTopics
  const topicGate = new Promise(resolve => { releaseTopics = resolve })
  await page.route('**/api/topics?**', async route => { await topicGate; await route.continue() })
  const topicRequest = page.waitForRequest(request => new URL(request.url()).pathname === '/api/topics')
  const topicResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/topics')
  await page.getByLabel('主题数量', { exact: true }).selectOption('4')
  await topicRequest
  try { assert.equal(await exportButton.isDisabled(), true, 'Report export must wait for the visible topic view, not only global statistics') }
  finally { releaseTopics() }
  await (await topicResponse).finished()
  await page.unroute('**/api/topics?**')
  await page.waitForFunction(() => document.querySelectorAll('[data-testid="topic-matrix"] thead button').length === 4)
  console.log('PASS Report export waits for independently loading visible views')
  await page.getByTestId('workspace-investigation').click()
  await page.getByRole('button', { name: '调查 Nadia Conti ↗', exact: true }).click()
  await count(26)
  await page.getByTestId('event-swimlane').waitFor()
  assert.equal(await page.locator('.event-map').evaluate(node => node.scrollWidth > node.clientWidth + 1), false,
    'Small-desktop event chart must fit its panel without losing the end of the timeline')
  console.log('PASS Small-desktop event chart fits the panel width')
  assert.deepEqual(errors, [])
} finally { await browser.close() }

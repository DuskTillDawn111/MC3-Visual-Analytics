import { chromium } from 'playwright'
import assert from 'node:assert/strict'

const base=process.env.MC3_BASE_URL||'http://127.0.0.1:8000'
const browser=await chromium.launch({channel:'msedge',headless:true})
const page=await browser.newPage({viewport:{width:1366,height:768}})
const errors=[];page.on('pageerror',error=>errors.push(error.message))
try{
 await page.goto(base,{waitUntil:'networkidle'})
 await page.getByTestId('workspace-investigation').click()
 const first=await (await page.request.get(base+'/api/events/timeline?page_size=100')).json()
 const events=[...first.items]
 for(let n=2;n<=Math.ceil(first.total/100);n++)events.push(...(await (await page.request.get(base+`/api/events/timeline?page_size=100&page=${n}`)).json()).items)
 await page.getByTestId('event-swimlane').waitFor()
 const marks=page.getByTestId('event-swimlane').locator('g.swimlane-event')
 assert.equal(await marks.count(),events.filter(row=>row.timestamp).length,'Event overview must cover the complete selected scope')
 const before=await marks.evaluateAll(nodes=>nodes.map(node=>node.getAttribute('aria-label')))
 const listFirst=await page.getByTestId('timeline-event').first().innerText()
 await page.locator('.event-pagination').getByRole('button',{name:'→',exact:true}).click()
 assert.notEqual(await page.getByTestId('timeline-event').first().innerText(),listFirst)
 assert.deepEqual(await marks.evaluateAll(nodes=>nodes.map(node=>node.getAttribute('aria-label'))),before)
 console.log('PASS Event overview covers all filtered events and stays fixed while the list paginates')
 await page.getByRole('button',{name:'调查 Nadia Conti ↗',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('.event-panel .panel-note')?.textContent.startsWith('15 个事件'))
 assert.equal(await marks.count(),13)
 await marks.filter({has:page.locator('circle')}).last().focus()
 await page.setViewportSize({width:1920,height:1080})
 await page.getByRole('button',{name:'放大事件图',exact:true}).click()
 assert.equal(await page.locator('.alias-panel').isVisible(),false)
 await page.waitForFunction(()=>document.querySelector('.event-day-chart')?.getBoundingClientRect().height<150)
 await page.getByTestId('workspace-groups').click()
 await page.setViewportSize({width:1366,height:768})
 assert.equal(await page.locator('.topics-panel').isVisible(),true)
 const network=await page.locator('.network').boundingBox(),topics=await page.locator('.topics-panel').boundingBox()
 assert(network&&topics&&topics.x>network.x+network.width-2&&Math.abs(topics.y-network.y)<2)
 await page.getByRole('button',{name:'放大关系图',exact:true}).click()
 assert.equal(await page.locator('.topics-panel').isVisible(),false)
 await page.getByRole('button',{name:'放大关系图',exact:true}).click()
 assert.equal(await page.locator('.topics-panel').isVisible(),true)
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 assert.deepEqual(errors,[])
 console.log('PASS Small desktop shows linked panels together and maximize returns to the same context')
 await page.setViewportSize({width:1920,height:1080})
 await page.getByRole('button',{name:'放大主题图',exact:true}).click()
 const matrix=await page.locator('.topic-table').boundingBox(),description=await page.locator('.topic-description').boundingBox()
 assert(matrix&&description&&description.x>=matrix.x+matrix.width,'Expanded topics should compare the matrix and original samples side by side')
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 console.log('PASS Expanded topic view uses the available width for matrix and original-sample comparison')
}finally{await browser.close()}
